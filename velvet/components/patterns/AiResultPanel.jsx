import React from 'react';
import { Badge } from '../display/Badge.jsx';
import { Button } from '../actions/Button.jsx';
import { SectionLabel } from '../primitives/SectionLabel.jsx';
import { Glyph } from '../primitives/Glyph.jsx';
import { CopyButton } from '../actions/CopyButton.jsx';
import { Skeleton, SkeletonText } from '../feedback/Skeleton.jsx';
import { cx } from '../primitives/cx.js';
const txt = (n) => (typeof n === 'string' || typeof n === 'number' ? String(n) : '');
export function AiResultPanel({ title = 'AI analysis', model, elapsed, status = 'done', error = 'The model didn’t return a result. Try again.', score, scoreMax = 100, scoreTone, headline, subline, summary, sections = [], sources = [], tokens, cost, disclaimer = 'Generated by AI — check important details before acting on them.', onRegenerate, onFeedback, feedback, onCopy, className }) {
  const [fb, setFb] = React.useState(feedback ?? null);
  React.useEffect(() => { if (feedback !== undefined) setFb(feedback); }, [feedback]);
  const streaming = status === 'streaming', failed = status === 'error';
  const hasScore = score != null;
  const pct = hasScore ? Math.max(0, Math.min(1, score / scoreMax)) : 0;
  const tone = scoreTone || (pct >= 0.75 ? 'success' : pct >= 0.5 ? 'warning' : 'danger');
  const empty = !hasScore && !headline && !summary && !sections.length;
  const S = 64, W = 6, R = (S - W) / 2, C = 2 * Math.PI * R;
  const plain = () => [headline, subline, summary, ...sections.map((s) => s.title + '\n' + (s.items || []).map((i) => '• ' + txt(i)).join('\n'))].filter(Boolean).join('\n\n');
  const vote = (v) => { const n = fb === v ? null : v; setFb(n); onFeedback && onFeedback(n); };
  const meta = [tokens != null ? Number(tokens).toLocaleString('en') + ' tokens' : null, cost].filter(Boolean).join(' · ');
  return (
    <article className={cx('vui-ai', streaming && 'vui-ai--streaming', className)} aria-busy={streaming || undefined}>
      <header className="vui-ai__head">
        <Badge tone="brand" className="vui-ai__chip" dot={streaming} pulse icon="sparkles">{streaming ? 'Analysing…' : title}</Badge>
        {(model || elapsed) && <span className="vui-ai__prov" title="Model · time">{[model, !streaming && elapsed].filter(Boolean).join(' · ')}</span>}
      </header>
      <div className="vui-ai__body" aria-live="polite">
        {failed ? (
          <div className="vui-ai__error" role="alert"><Glyph name="triangle-alert" /><div>{error}</div>{onRegenerate && <Button variant="secondary" size="sm" onClick={onRegenerate}>Retry</Button>}</div>
        ) : streaming && empty ? (
          <>
            <div className="vui-ai__skel"><Skeleton circle height={S} /><div style={{ flex: 1, display: 'grid', gap: 8 }}><Skeleton width="45%" height={14} /><Skeleton width="65%" height={11} /></div></div>
            <div className="vui-ai__secs"><SkeletonText lines={3} /><SkeletonText lines={3} /></div>
          </>
        ) : (
          <>
            {(hasScore || headline) && (
              <div className="vui-ai__score-row">
                {hasScore && (
                  <span className={'vui-ring vui-progress--' + tone} style={{ width: S, height: S }} role="img" aria-label={'Score ' + score + ' of ' + scoreMax}>
                    <svg width={S} height={S} viewBox={'0 0 ' + S + ' ' + S} aria-hidden="true"><circle className="vui-ring__track" cx={S / 2} cy={S / 2} r={R} strokeWidth={W} /><circle className="vui-ring__bar" cx={S / 2} cy={S / 2} r={R} strokeWidth={W} strokeDasharray={C} strokeDashoffset={C * (1 - pct)} /></svg>
                    <span className="vui-ring__value vui-ai__score" aria-hidden="true">{score}</span>
                  </span>
                )}
                <div style={{ minWidth: 0 }}>{headline && <h3 className="vui-ai__headline">{headline}</h3>}{subline && <div className="vui-ai__subline">{subline}</div>}</div>
              </div>
            )}
            {summary && <p className="vui-ai__summary">{summary}</p>}
            {sections.length > 0 && (
              <div className="vui-ai__secs">
                {sections.map((s, k) => (
                  <section key={s.title || k} className={cx('vui-ai__sec', s.tone && 'vui-ai__sec--' + s.tone)}>
                    <SectionLabel as="h4" className="vui-ai__sec-h" tone="secondary" icon={s.icon} end={<span>{(s.items || []).length}</span>}>{s.title}</SectionLabel>
                    <ul className="vui-ai__items">{(s.items || []).map((it, i) => <li key={i}>{it}</li>)}</ul>
                  </section>
                ))}
              </div>
            )}
            {streaming && <SkeletonText lines={2} lastWidth="40%" />}
            {sources.length > 0 && (
              <div><SectionLabel as="h4" className="vui-ai__sec-h">Sources</SectionLabel>
                <ol className="vui-ai__sources">{sources.map((s, i) => { const In = s.href ? 'a' : 'span'; return <li key={i}><In className="vui-ai__src" href={s.href} target={s.href ? '_blank' : undefined} rel={s.href ? 'noreferrer' : undefined} title={s.detail || s.label}><b>{i + 1}</b><span>{s.label}</span></In></li>; })}</ol>
              </div>
            )}
            {disclaimer && !streaming && <p className="vui-ai__disclaimer">{disclaimer}</p>}
          </>
        )}
      </div>
      {!failed && (
        <footer className="vui-ai__foot">
          {!streaming && <CopyButton value={plain} variant="ghost" size="sm" onCopy={onCopy} />}
          {!streaming && onRegenerate && <Button variant="ghost" size="sm" iconLeft="refresh" onClick={onRegenerate}>Regenerate</Button>}
          {!streaming && onFeedback && (
            <span className="vui-ai__fb" role="group" aria-label="Was this helpful?"><span>Helpful?</span>
              <Button variant="ghost" size="sm" aria-pressed={fb === 'up'} onClick={() =>vote('up')}>Yes</Button>
              <Button variant="ghost" size="sm" aria-pressed={fb === 'down'} onClick={() =>vote('down')}>No</Button>
            </span>
          )}
          {streaming && <span className="vui-ai__meta" style={{ marginLeft: 0 }}>Writing…</span>}
          {meta && !streaming && <span className="vui-ai__meta">{meta}</span>}
        </footer>
      )}
    </article>
  );
}
