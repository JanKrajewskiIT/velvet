import { For, type JSX, Match, mergeProps, Show, Switch } from 'solid-js';

import { createControllable } from '../../hooks/createControllable';
import { useTranslate } from '../../i18n/useTranslate';
import { cx } from '../../utils/cx';
import { Polymorphic } from '../../utils/polymorphic';
import { Button } from '../actions/Button';
import { Badge } from '../display/Badge';
import { Skeleton } from '../feedback/Skeleton';
import { SkeletonText } from '../feedback/SkeletonText';
import { Glyph } from '../primitives/Glyph';
import { SectionLabel } from '../primitives/SectionLabel';
import { AiResultFooter } from './AiResultFooter';
import { aiResultPlainText, RING_SIZE } from './aiResultFormat';
import { AiResultScoreRow } from './AiResultScoreRow';
import { AiResultSections } from './AiResultSections';
import type { AiFeedback, AiScoreTone, AiSection, AiSource } from './aiResultTypes';

export type { AiFeedback, AiScoreTone, AiSection, AiSource } from './aiResultTypes';

export interface AiResultPanelProps {
  /** @default localized "AI analysis" */
  title?: string;
  model?: string;
  elapsed?: string;
  /** @default 'done' */
  status?: 'streaming' | 'done' | 'error';
  /** @default localized "The model didn’t return a result. Try again." */
  error?: JSX.Element;
  score?: number;
  /** @default 100 */
  scoreMax?: number;
  /** Default: ≥75% success, ≥50% warning, else danger */
  scoreTone?: AiScoreTone;
  headline?: JSX.Element;
  subline?: JSX.Element;
  summary?: JSX.Element;
  sections?: AiSection[];
  sources?: AiSource[];
  tokens?: number;
  /** Preformatted, e.g. "$0.0021" */
  cost?: string;
  /** Pass '' to hide. @default localized "Generated by AI — check important details before acting on them." */
  disclaimer?: string;
  onRegenerate?: () => void;
  /** Shows Helpful? Yes / No; null when un-voted */
  onFeedback?: (value: AiFeedback) => void;
  /** Controlled vote; omit to let the panel keep it. */
  feedback?: AiFeedback;
  onCopy?: (text: string) => void;
  class?: string;
}

/** Surface for a structured (non-chat) model answer: provenance, score ring, findings, sources, copy / regenerate / feedback and cost meta. */
export const AiResultPanel = (props: AiResultPanelProps) => {
  const p = mergeProps({ status: 'done', scoreMax: 100 } satisfies AiResultPanelProps, props);
  const translate = useTranslate();
  const title = () => p.title ?? translate('velvet.patterns.aiResultPanel.title');
  const error = () => p.error ?? translate('velvet.patterns.aiResultPanel.error');
  const disclaimer = () => p.disclaimer ?? translate('velvet.patterns.aiResultPanel.disclaimer');
  const [vote, setVote] = createControllable<AiFeedback>({
    value: () => p.feedback,
    defaultValue: null,
    onChange: (next) => p.onFeedback?.(next),
  });

  const streaming = () => p.status === 'streaming';
  const hasScore = () => p.score != null;
  const sections = () => p.sections ?? [];
  const sources = () => p.sources ?? [];
  const empty = () => !hasScore() && !p.headline && !p.summary && sections().length === 0;
  const provenance = () => [p.model, !streaming() && p.elapsed].filter(Boolean).join(' · ');
  const plain = () =>
    aiResultPlainText({ headline: p.headline, subline: p.subline, summary: p.summary, sections: sections() });
  const toggleVote = (value: 'up' | 'down') => setVote(vote() === value ? null : value);

  return (
    <article class={cx('vui-ai', streaming() && 'vui-ai--streaming', p.class)} aria-busy={streaming() || undefined}>
      <header class="vui-ai__head">
        <Badge tone="brand" class="vui-ai__chip" dot={streaming()} pulse icon="sparkles">
          {streaming() ? translate('velvet.patterns.aiResultPanel.analysing') : title()}
        </Badge>
        <Show when={p.model || p.elapsed}>
          <span class="vui-ai__prov" title={translate('velvet.patterns.aiResultPanel.provenanceTitle')}>
            {provenance()}
          </span>
        </Show>
      </header>
      <div class="vui-ai__body" aria-live="polite">
        <Switch
          fallback={
            <>
              <AiResultScoreRow
                score={p.score}
                max={p.scoreMax}
                tone={p.scoreTone}
                headline={p.headline}
                subline={p.subline}
              />
              <Show when={p.summary}>
                <p class="vui-ai__summary">{p.summary}</p>
              </Show>
              <AiResultSections sections={sections()} />
              <Show when={streaming()}>
                <SkeletonText lines={2} lastWidth="40%" />
              </Show>
              <Show when={sources().length > 0}>
                <div>
                  <SectionLabel as="h4" class="vui-ai__sec-h">
                    {translate('velvet.patterns.aiResultPanel.sources')}
                  </SectionLabel>
                  <ol class="vui-ai__sources">
                    <For each={sources()}>
                      {(source, index) => (
                        <li>
                          <Polymorphic
                            tag={source.href ? 'a' : 'span'}
                            class="vui-ai__src"
                            href={source.href}
                            target={source.href ? '_blank' : undefined}
                            rel={source.href ? 'noreferrer' : undefined}
                            title={source.detail || source.label}
                          >
                            <b>{index() + 1}</b>
                            <span>{source.label}</span>
                          </Polymorphic>
                        </li>
                      )}
                    </For>
                  </ol>
                </div>
              </Show>
              <Show when={disclaimer() && !streaming()}>
                <p class="vui-ai__disclaimer">{disclaimer()}</p>
              </Show>
            </>
          }
        >
          <Match when={p.status === 'error'}>
            <div class="vui-ai__error" role="alert">
              <Glyph name="triangle-alert" />
              <div>{error()}</div>
              <Show when={p.onRegenerate}>
                <Button variant="secondary" size="sm" onClick={() => p.onRegenerate?.()}>
                  {translate('velvet.common.retry')}
                </Button>
              </Show>
            </div>
          </Match>
          <Match when={streaming() && empty()}>
            <div class="vui-ai__skel">
              <Skeleton circle height={RING_SIZE} />
              <div style={{ flex: 1, display: 'grid', gap: 'var(--space-2)' }}>
                <Skeleton width="45%" height={14} />
                <Skeleton width="65%" height={11} />
              </div>
            </div>
            <div class="vui-ai__secs">
              <SkeletonText lines={3} />
              <SkeletonText lines={3} />
            </div>
          </Match>
        </Switch>
      </div>
      <Show when={p.status !== 'error'}>
        <AiResultFooter
          streaming={streaming()}
          plain={plain}
          tokens={p.tokens}
          cost={p.cost}
          feedback={vote()}
          feedbackEnabled={!!p.onFeedback}
          onToggleFeedback={toggleVote}
          onCopy={p.onCopy}
          onRegenerate={p.onRegenerate}
        />
      </Show>
    </article>
  );
};
